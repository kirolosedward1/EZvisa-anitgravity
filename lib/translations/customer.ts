export function customerText(locale: Locale, key: CustomerKey, values?: Record<string, string | number>) {
  return fill(catalogs[locale][key], values)
}

export function statusText(locale: Locale, label: string) {
  const key = STATUS_KEY[label]
  return key ? customerText(locale, key) : label
}
